// Builds dist/ems-esp-heatpump-energy-card.js: model + card in one file, no dependencies.
// Usage: node build.mjs            (write the bundle)
//        node build.mjs --check    (fail if the committed bundle is out of date)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";

const dir = new URL(".", import.meta.url);
const read = (p) => readFileSync(new URL(p, dir), "utf8");
const model = read("src/model.js").replace(/^export /gm, "");
const card = read("src/card.js").replace(/^import .*"\.\/model\.js";\n/m, "");
const out = `// GENERATED by build.mjs – do not edit. Source: src/model.js + src/card.js\n${model}\n${card}`;
const target = new URL("dist/ems-esp-heatpump-energy-card.js", dir);

if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== out) {
    console.error("dist/ems-esp-heatpump-energy-card.js is out of date – run `node build.mjs`.");
    process.exit(1);
  }
  console.log("dist bundle is up to date");
} else {
  mkdirSync(new URL("dist/", dir), { recursive: true });
  writeFileSync(target, out);
  console.log("dist/ems-esp-heatpump-energy-card.js written");
}
